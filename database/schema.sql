-- Cada usuário autenticado só pode ler ou alterar suas próprias respostas.
create table if not exists public.usuarios (
  id_usuario bigint generated by default as identity primary key,
  nome varchar not null,
  email varchar not null,
  senha varchar
);

-- Link public.usuarios rows to real Supabase Auth accounts by email.
-- Passwords belong only in Auth; the legacy senha column is cleared when linked.
alter table public.usuarios
  add column if not exists auth_user_id uuid references auth.users (id) on delete cascade;

alter table public.usuarios alter column senha drop not null;
create unique index if not exists usuarios_auth_user_id_uidx
  on public.usuarios (auth_user_id) where auth_user_id is not null;

alter table public.usuarios enable row level security;
revoke all on public.usuarios from public, anon, authenticated;
grant select (auth_user_id, nome, email), update (nome)
  on public.usuarios to authenticated;

do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'usuarios'
  loop
    execute format('drop policy %I on public.usuarios', existing_policy.policyname);
  end loop;
end;
$$;

create policy "Users read own profile"
  on public.usuarios for select to authenticated
  using (auth.uid() = auth_user_id);

create policy "Users update own profile"
  on public.usuarios for update to authenticated
  using (auth.uid() = auth_user_id)
  with check (auth.uid() = auth_user_id);

create or replace function public.sync_auth_user_to_usuarios()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  linked_rows integer;
  profile_name text;
begin
  profile_name := coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1));

  update public.usuarios
  set auth_user_id = new.id,
      nome = coalesce(nullif(profile_name, ''), nome),
      email = new.email,
      senha = null
  where id_usuario = (
    select candidate.id_usuario
    from public.usuarios as candidate
    where lower(candidate.email) = lower(new.email)
      and (candidate.auth_user_id is null or candidate.auth_user_id = new.id)
    order by candidate.id_usuario
    limit 1
  );
  get diagnostics linked_rows = row_count;

  if linked_rows = 0 then
    insert into public.usuarios (auth_user_id, nome, email, senha)
    values (new.id, profile_name, new.email, null);
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_sync_usuarios on auth.users;
create trigger on_auth_user_created_sync_usuarios
  after insert on auth.users
  for each row execute function public.sync_auth_user_to_usuarios();

