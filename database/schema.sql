-- Forum author names, per-user likes, and ownership-based deletion.
-- Create the forum tables when setting up a new Supabase project. These
-- definitions also match the columns queried by forumService.ts.
create table if not exists public.postagens_forum (
  id uuid primary key default gen_random_uuid(),
  titulo text not null,
  conteudo text not null,
  id_usuario uuid not null references auth.users (id) on delete cascade,
  criado_em timestamptz not null default now()
);

create table if not exists public.respostas_forum (
  id uuid primary key default gen_random_uuid(),
  id_postagem uuid not null references public.postagens_forum (id) on delete cascade,
  id_usuario uuid not null references auth.users (id) on delete cascade,
  conteudo text not null,
  criado_em timestamptz not null default now()
);

-- Add fields when upgrading an existing forum schema.
alter table public.postagens_forum add column if not exists nome_autor text;
alter table public.postagens_forum add column if not exists avatar_id text;
alter table public.postagens_forum add column if not exists categoria text not null default 'Dicas';
-- Guarda se cada publicação aceita comentários.
alter table public.postagens_forum add column if not exists permite_comentarios boolean not null default true;
-- Guarda o endereço público da foto anexada à publicação, se houver.
alter table public.postagens_forum add column if not exists imagem_url text;
alter table public.respostas_forum add column if not exists autor_nome text;
alter table public.respostas_forum add column if not exists autor_avatar text;
alter table public.respostas_forum add column if not exists id_comentario_pai uuid references public.respostas_forum (id) on delete cascade;

create table if not exists public.curtidas_forum (
  id_postagem uuid not null references public.postagens_forum (id) on delete cascade,
  id_usuario uuid not null references auth.users (id) on delete cascade,
  criado_em timestamptz not null default now(),
  primary key (id_postagem, id_usuario)
);

alter table public.postagens_forum enable row level security;
alter table public.respostas_forum enable row level security;
alter table public.curtidas_forum enable row level security;

-- Cria o bucket público para exibir fotos do fórum no feed de toda a comunidade.
insert into storage.buckets (id, name, public)
values ('forum-images', 'forum-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Forum images are publicly readable" on storage.objects;
create policy "Forum images are publicly readable"
  on storage.objects for select using (bucket_id = 'forum-images');

drop policy if exists "Forum users upload own images" on storage.objects;
create policy "Forum users upload own images"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'forum-images' and (storage.foldername(name))[1] = auth.uid()::text);

