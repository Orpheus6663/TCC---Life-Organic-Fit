  on public.postagens_forum for insert to authenticated
  with check (auth.uid() = id_usuario);

drop policy if exists "Forum users insert own comments" on public.respostas_forum;
create policy "Forum users insert own comments"
  on public.respostas_forum for insert to authenticated
  with check (
    auth.uid() = id_usuario
    -- Só permite inserir comentários na publicação quando a opção estiver ligada.
    and exists (
      select 1 from public.postagens_forum
      where postagens_forum.id = id_postagem
        and postagens_forum.permite_comentarios = true
    )
  );

