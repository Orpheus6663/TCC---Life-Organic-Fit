-- Centraliza as denúncias para que a equipe admin possa analisá-las entre sessões.
create table if not exists public.denuncias_forum (
  id uuid primary key default gen_random_uuid(),
  id_postagem uuid not null references public.postagens_forum (id) on delete cascade,
  id_denunciante uuid references auth.users (id) on delete set null,
  motivo text not null,
  criada_em timestamptz not null default now(),
  unique (id_postagem, id_denunciante)
);

alter table public.denuncias_forum enable row level security;
grant select, insert, delete on public.denuncias_forum to authenticated;

drop policy if exists "Users submit forum reports" on public.denuncias_forum;
create policy "Users submit forum reports"
  on public.denuncias_forum for insert to authenticated
  with check (auth.uid() = id_denunciante);

drop policy if exists "Admins read forum reports" on public.denuncias_forum;
create policy "Admins read forum reports"
  on public.denuncias_forum for select to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins resolve forum reports" on public.denuncias_forum;
create policy "Admins resolve forum reports"
  on public.denuncias_forum for delete to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

